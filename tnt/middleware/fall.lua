--- Падение шага цепочки: отказ, который несёт стек места броска.
---
--- Цепочка зовёт каждый шаг под перехватом и брошенное превращает
--- в отказ: падение третьего слоя не отменяет выхода первых двух. Но
--- перехват разматывает стек, и после него «как туда пришли» уже
--- не узнать: при поломке в общей функции, которую зовут из десяти мест,
--- вызывающий неизвестен. Поэтому стек снимает ловушка `xpcall` —
--- на месте броска, пока он ещё есть, — и отказ несёт его дальше.
---
--- Отказ — таблица `{ message, traceback }`, а не строка со стеком
--- внутри. Стек нужен одной записи — о самой поломке, — а отказ попадает
--- и в запись о проходе, и в отрезок трассы, и в ответ: строка со стеком
--- растянула бы каждую из них вдвое. Таблица отдаёт стек тому, кто его
--- спросит по имени поля, а печатается своим словом: `tostring(err)`
--- и журнал видят строку «слой «audit» упал: …», без стека.
---
---     local _, err = chain:run(request, handler)
---
---     tostring(err)   --> 'обработчик упал: app.lua:12: нет такого поля'
---     err.traceback   --> '\nstack traceback:\n\t[C]: in function …'
---
--- Вид `{ message, traceback }` — общий у отказов со стеком: слово
--- в `message`, стек в `traceback`. Кто читает стек у одного такого
--- отказа, прочтёт его и у этого.
---
--- Само брошенное отказ держит полем `raised` — как бросили. Бросают
--- не только поломку: обработчик вправе и отказать броском — «нет такого
--- клиента» со статусом 404, — и в слове упавшего шага от такого отказа
--- остаётся одна строка, без статуса и без кода. Тот, кто превращает
--- отказ в ответ, судит по брошенному, и отказ, брошенный обработчиком,
--- отвечает тем же, чем ответил бы, вернись он парой `nil, err`.
---
---     local _, err = chain:run(request, function()
---         error({ status = 404, message = 'нет такого клиента' })
---     end)
---
---     tostring(err)   --> 'обработчик упал: нет такого клиента'
---     err.raised      --> { status = 404, message = 'нет такого клиента' }

local Module = {}

--- Отказ упавшего шага.
---@class TntMiddlewareFall
---@field message string Что сказано о падении: «обработчик упал: …»
---@field traceback string Стек на месте броска: строка `debug.traceback`
---@field raised any Что бросили — как есть; у отказа упавшего шага, брошенного заново, — брошенное первым
local Fall = {}

--- Печать отказа — его слово, без стека.
---
--- Кто печатает отказ — журнал, текст ответа, `tostring` в чужом коде, —
--- тот получает ровно прежнюю строку, а стек берёт полем только тот,
--- кому он нужен.
---@param self TntMiddlewareFall
---@return string
function Fall.__tostring(self)
    return self.message
end

--- Читаемый текст брошенного.
---
--- Брошено может быть что угодно: строка, объект ошибки Tarantool,
--- своя таблица. Строка и объект ошибки печатают себя сами, а у таблицы
--- текст лежит в `message`: без него от неё осталось бы «table: 0x...»,
--- по которому не понять ничего.
---@param raised any
---@return string
local function describe(raised)
    if type(raised) == 'table' and raised.message ~= nil then
        return tostring(raised.message)
    end

    return tostring(raised)
end

--- Ловушка `xpcall` для шага с этим именем.
---
--- Зовётся она на месте броска, до размотки, — и только там стек ещё
--- есть. Имя шага приходит при сборке прохода, а не при падении: оно
--- от запроса к запросу не меняется, и ловушка на слой строится один раз.
---
--- Сорвись сама ловушка — печать брошенного бросила, кончилась память, —
--- `xpcall` отдаст вместо отказа слово Lua строкой. Цепочка и тогда
--- не бросает: такое слово — тоже отказ, только без стека.
---
--- Отказ упавшего шага, брошенный заново — слой получил его от `next`
--- и сделал `error(err)`, — отдаёт новому своё брошенное: бросили
--- дальше то же самое, и отказ, брошенный обработчиком, обязан дойти
--- своим до того, кто превращает его в ответ, через сколько бы слоёв
--- его ни перебросили. Слово и стек при этом у нового свои: слово
--- вложенное, стек — места последнего броска.
---@param what string Как назвать шаг: «обработчик упал», «слой «audit» упал»
---@return fun(raised: any): TntMiddlewareFall
function Module.trap(what)
    return function(raised)
        local origin = raised

        if Module.is(raised) then
            origin = raised.raised
        end

        return setmetatable({
            message = ('%s: %s'):format(what, describe(raised)),
            -- Уровень 2: первый — сама ловушка, и в стеке она не нужна.
            traceback = debug.traceback('', 2),
            raised = origin,
        }, Fall)
    end
end

--- Отказ ли это упавшего шага.
---
--- Узнаётся по метатаблице, а не по полям: `{ message, traceback }`
--- бывает и у чужого отказа, и чей он, по полям не сказать.
---@param value any
---@return boolean
function Module.is(value)
    return getmetatable(value) == Fall
end

return Module
