--- Слой перехвата: отказ становится ответом.
---
--- Сама цепочка исключений наружу не выпускает: упавший слой она приводит
--- к отказу. Но отказ — это ещё не ответ, а вызывающему нужен именно
--- ответ: клиент, которому не ответили ничем, ждёт до собственного срока
--- и повторяет запрос, добавляя нагрузки узлу, которому и так плохо.
---
--- Чем отвечать, знает только приложение: конвейеру неизвестно, ответ
--- это HTTP или запись в очередь. Поэтому ответчик задаётся настройкой,
--- а без него слой остаётся тем, чем полезен и сам по себе, — местом,
--- где всякий сорвавшийся запрос попадает в журнал ровно один раз.
---
--- Ставить его надо выше тех слоёв, чьи падения он должен ловить, —
--- то есть обычно первым или сразу за опознавателем запроса.
---
--- **Отказ отказу рознь.** «Не вошли», «нет права», «нет такого» — это
--- работа узла, а не беда его; падение хранилища — беда. Писать о них
--- одним уровнем значит утопить второе в первом: дежурный, глядящий
--- на записи уровня error, увидит там чужие опечатки в пароле. Хуже
--- того, применявший пакет перестаёт возвращать ожидаемые отказы парой
--- `nil, err` — лишь бы они не попали в журнал ошибок, — и договор
--- отказа ломается на самой границе, ради которой он и заведён.
---
--- Различает их слой сам, по признаку в самом отказе, а не по каталогу
--- кодов отказов. Каталог стал бы зависимостью конвейера, а за ним —
--- всякого, кто берёт конвейер, и основание перестало бы браться
--- отдельно. Признаков два, и оба — обычные поля, а не чужой тип:
--- `expected` говорит прямо, а статус ниже пятисот говорит, что это ответ
--- клиенту о его запросе, а не рассказ о нашей поломке. Отказ упавшего
--- шага судится по тому, что бросили: ожидаемый отказ, брошенный
--- обработчиком, остаётся ожидаемым. Приложению, у которого отказы
--- устроены иначе, довольно своего приговора `level_of(err)`.
---
--- Отказ упавшего шага пишется со стеком места броска — отдельным полем
--- `traceback`: запись перехвата и есть та единственная запись о поломке,
--- по которой дежурный ищет, как туда пришли. Ожидаемый отказ, брошенный
--- обработчиком, пишется без стека, как и возвращённый парой: поломки
--- за ним нет. Стек чужого отказа слой не выписывает: о поломке с таким
--- стеком уже написал тот, кто её завёл, и вторая копия стека в журнале —
--- вдвое больше строк без нового смысла.

local common = require('tnt.middleware.layer.common')
local fall = require('tnt.middleware.fall')

local Module = {}

--- Уровень записи об ожидаемом отказе.
---
--- Предупреждение, а не ошибка: клиент, ушедший с 403, — это работа узла.
Module.EXPECTED_LEVEL = 'warn'

--- Уровень записи о поломке.
Module.BREAKDOWN_LEVEL = 'error'

--- Статус, с которого начинаются поломки: 5xx — «у нас не вышло»,
--- всё, что ниже, — ответ клиенту о его запросе.
local BREAKDOWN_STATUS = 500

--- Что сказано в записи о поломке и что — об ожидаемом отказе.
local BROKE = 'запрос сорвался'
local REFUSED = 'запрос отклонён'

--- Каким уровнем писать об отказе.
---
--- Отказ упавшего шага судится по брошенному (`raised`): обработчик
--- вправе отказать и броском, а «нет такого клиента» — работа узла,
--- как его ни отдай, парой или броском. Своих признаков у отказа
--- упавшего шага нет, и без этого всякий брошенный отказ писался бы
--- уровнем `error`.
---@param err any
---@return string
function Module.level_of(err)
    if type(err) ~= 'table' then
        -- Про строку известно лишь то, что её сочинил отказавший, и
        -- признака ожидаемости в ней нет. Считать её ожидаемой — значит
        -- спрятать поломку среди предупреждений, то есть ровно то,
        -- от чего этот приговор и заведён.
        return Module.BREAKDOWN_LEVEL
    end

    if fall.is(err) then
        return Module.level_of(err.raised)
    end

    if type(err.expected) == 'boolean' then
        return err.expected and Module.EXPECTED_LEVEL or Module.BREAKDOWN_LEVEL
    end

    if type(err.status) == 'number' and err.status < BREAKDOWN_STATUS then
        return Module.EXPECTED_LEVEL
    end

    return Module.BREAKDOWN_LEVEL
end

---@class TntMiddlewareRescueOptions
---@field tag string|nil Метка журнала
---@field describe (fun(context: any): table|nil)|nil Чем описать запрос
---@field respond (fun(context: any, err: any): any)|nil Чем отвечать на отказ
---@field level_of (fun(err: any): string)|nil Каким уровнем писать об отказе

--- Собирает слой перехвата.
---@param opts TntMiddlewareRescueOptions|nil
---@return TntMiddlewareFn
function Module.new(opts)
    local options = opts or {}
    local respond = options.respond

    common.callable(respond, 'ответчик — функция (context, err) -> ответ')
    common.callable(options.level_of, 'приговор об уровне — функция (err) -> уровень')
    common.callable(options.describe, 'описатель запроса — функция (context) -> поля')

    local level_of = options.level_of or Module.level_of
    local journal = common.journal(options)

    return function(context, next_layer)
        local response, err = next_layer(context)

        if err == nil then
            return response
        end

        -- Под pcall — только описатель: он приходит от приложения и бросить
        -- вправе. Сама запись идёт вне pcall, прямо из этой функции: так
        -- журнал ядра называет местом записи строку слоя.
        local described, fields = pcall(common.fields_of, options, context)

        if described then
            fields.err = err

            -- Приговор зовётся здесь, а не выше: он приходит от
            -- приложения, и сорвавшийся приговор не должен стоить
            -- ответа — ровно как и сама запись.
            --
            -- И под своим pcall: сорвись он вместе с описателем — не
            -- осталось бы об отказе ни слова. Это та же тишина, от которой
            -- защищает откат на неизвестном уровне ниже, только полная.
            local judged, verdict = pcall(level_of, err)
            local level = Module.BREAKDOWN_LEVEL

            if judged then
                level = verdict
            else
                -- Отказ приговора идёт в ту же запись, а не в отдельную:
                -- две записи об одном отказе читаются как два отказа.
                fields.level_of = tostring(verdict)
            end

            -- Стек нужен записи о поломке, и только ей: ожидаемый отказ,
            -- брошенный обработчиком, пишется так же, как возвращённый
            -- парой, — без стека, иначе каждое «нет такого клиента»
            -- тянуло бы в журнал экран кадров.
            if fall.is(err) and level ~= Module.EXPECTED_LEVEL then
                fields.traceback = err.traceback
            end

            -- Уровень, которого журнал не знает, понижать нельзя:
            -- опечатка в приговоре увела бы поломку в тишину.
            local write = journal[level] or journal[Module.BREAKDOWN_LEVEL]

            -- Слова идут за уровнем: «сорвался» — про нас, «отклонён» —
            -- про клиента. Дежурный ищет в журнале первое, и второе
            -- не должно попадаться ему по дороге.
            write(level == Module.EXPECTED_LEVEL and REFUSED or BROKE, fields)
        else
            common.failed(journal, 'записать об отказе', fields)
        end

        if respond == nil then
            return nil, err
        end

        local answer = respond(context, err)

        -- Ответчик, вернувший пустоту, отказ не гасит: иначе вызывающий
        -- получил бы ни ответа, ни причины — худший из возможных исходов.
        if answer == nil then
            return nil, err
        end

        return answer
    end
end

return Module
