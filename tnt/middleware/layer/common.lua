--- Общее для готовых слоёв: часы, журнал и описание запроса.
---
--- Слои пишутся по одному образцу: засечь время вокруг остатка цепочки,
--- собрать поля записи и сделать своё побочное дело так, чтобы оно
--- не стоило запроса. Повторённый в каждом слое, этот образец в каждом же
--- и расходится — то часы окажутся стенными, то сорвавшийся приёмник
--- метрик отменит удачный ответ.
---
--- Средства (часы и выдача опознавателей) берутся отсюда через внешнюю зависимость:
--- проверке довольно подменить их в одном месте на все слои сразу.
--- Опознаватель по умолчанию — ULID из `tnt-id`: в нём время в старших
--- знаках, и записи журнала одного узла сортируются по нему в порядке
--- запросов; у `uuid.str` ядра, четвёртой версии, порядка нет.

local clock = require('tnt.clock')
local context = require('tnt.context')
local id = require('tnt.id')
local log = require('tnt.log')
local external = require('tnt.external')

local Module = {}

--- Поле запроса, в котором живёт опознаватель.
---
--- Имя общее для всех слоёв: слой заголовка ответа ищет опознаватель там
--- же, куда его кладёт слой опознавателя, иначе ответ и журнал разойдутся.
--- Журнал опознаватель здесь не ищет — он берёт его из контекста файбера
--- (`tnt-context`), куда тот же слой кладёт его второй раз.
Module.REQUEST_FIELD = 'request_id'

--- Заголовок, которым опознаватель ходит между узлами.
---
--- Имя объявлено у ключа контекста `request_id`: под ним опознаватель
--- уезжает через `context.export()`, и второе место для того же имени
--- разошлось бы с первым.
Module.REQUEST_HEADER = context.REQUEST_ID_HEADER

--- Имя журнала, если ни реестр, ни слой не назвали своё.
---
--- Полное имя модуля, а не короткая метка: оно уходит встроенному журналу
--- как есть, и по нему оператор задаёт уровень в `log.modules`, где карта
--- плоская и `tnt` на `tnt.middleware` не действует.
Module.DEFAULT_TAG = 'tnt.middleware'

local source = external.install(Module, {
    monotonic = clock.monotonic,
    identifier = id.ulid,
})

--- Проверяет, что настройка, если она задана, — функция.
---
--- Проверка стоит при сборке слоя, а не при первом запросе: настройка
--- пишется кодом, и опечатка в ней обязана обнаружиться при объявлении
--- цепочки — когда отвечать ещё некому.
---
--- Текст отказа приходит целиком от слоя: у каждой настройки свои аргументы
--- и свой исход, и «настройка — функция» не сказало бы, какая именно
--- и какой она должна быть.
---
--- Отказ винит того, кто собрал слой: строку приложения, а не строку
--- фабрики внутри пакета, куда искать опечатку незачем. Фабрика зовёт
--- проверку отдельным предложением, а не хвостом: хвостовой вызов снял бы
--- кадр фабрики, и вина ушла бы кадром дальше.
---@param value any
---@param what string Чем настройка должна быть; войдёт в текст отказа
function Module.callable(value, what)
    if value ~= nil and type(value) ~= 'function' then
        -- Первый уровень — эта функция, второй — фабрика, третий — тот,
        -- кто её позвал. Реестр зовёт фабрику под `pcall`, у кадра
        -- `pcall` строки нет, и место — строку объявления цепочки —
        -- приписывает вход реестра.
        error(('%s, а не %s'):format(what, type(value)), 3)
    end
end

--- Текст отказа негодной метке журнала; у годной и у пустой — nil.
---
--- Метка уходит журналу именем, и правило берётся у журнала: своя копия
--- правила однажды разошлась бы с ним. Текст один на реестр и на слой:
--- метка реестра доходит до слоя той же настройкой `tag`, и два текста
--- об одной ошибке читались бы как две разные.
---@param tag any
---@return string|nil
function Module.tag_refusal(tag)
    if tag == nil or log.is_name(tag) then
        return nil
    end

    return ('метка журнала — имя журнала: %s, а не %q'):format(log.NAME_RULE, tostring(tag))
end

--- Журнал слоя.
---
--- Метка сверяется здесь, а не оставляется журналу: отказ `tnt-log`
--- винит того, кто позвал его, — фабрику слоя внутри пакета, — а виновна
--- строка, которая слой собрала.
---@param options table
---@return table
function Module.journal(options)
    local refusal = Module.tag_refusal(options.tag)

    if refusal ~= nil then
        -- Уровень тот же, что у `callable`, и по той же причине: фабрика
        -- зовёт журнал отдельным предложением.
        error(refusal, 3)
    end

    return log.new(options.tag or Module.DEFAULT_TAG)
end

--- Новый опознаватель запроса.
---@return string
function Module.identifier()
    return source().identifier()
end

--- Зовёт остаток цепочки, засекая, сколько он занял.
---@param act fun(): any, any
---@return any response
---@return any err
---@return number seconds
function Module.timed(act)
    -- Длительность меряется монотонными часами: перевод стенных часов
    -- назад посреди запроса дал бы отрицательную длительность, а перевод
    -- вперёд — час вместо миллисекунды.
    local started = source().monotonic()
    local response, err = act()

    return response, err, source().monotonic() - started
end

--- Сообщает, что побочное дело слоя не удалось.
---
--- Метка пишется неопределённой формой — «записать о запросе», —
--- потому что складывается она с «не удалось»: существительное в этом
--- месте расходится с ним в роде и читается как оборванная строка.
---
--- Запись идёт хвостовым вызовом: журнал ядра берёт место записи из кадра
--- того, кто позвал, и хвостовой вызов оставляет в нём строку слоя, а не
--- эту. Иначе все неудачи всех слоёв указывали бы сюда.
---@param journal table
---@param what string Что не удалось сделать: «записать о запросе»
---@param err any Чем сорвалось
function Module.failed(journal, what, err)
    return journal.warn(('%s не удалось'):format(what), { err = tostring(err) })
end

--- Делает побочное дело слоя, не роняя из-за него запрос.
---
--- Метрика и укладка заголовка не стоят ответа: сорвавшийся приёмник
--- превратил бы удачный ответ в отказ, и беда приёмника стала бы бедой
--- всего конвейера. Поэтому о ней сообщается, а запрос идёт дальше.
---
--- Под `pcall` — только само дело: оно приходит от приложения и бросить
--- вправе. Запись в журнал под `pcall` не кладётся никогда: журнал не
--- бросает, а `pcall` вокруг записи перевёл бы её место в `[C]:-1`.
---@param journal table
---@param what string Что не удалось сделать: «отдать замер времени запроса»
---@param act fun()
function Module.aside(journal, what, act)
    local ok, err = pcall(act)

    if ok then
        return
    end

    return Module.failed(journal, what, err)
end

--- Поля записи журнала об этом проходе.
---
--- Что за запрос — знает только тот, кто его завёл: конвейеру запрос
--- непрозрачен. Поэтому подробности даёт описатель из настроек слоя.
--- Опознаватель запроса в поля не кладётся: он приходит в запись верхним
--- полем из контекста файбера, куда его положил слой `request_id`,
--- а два места для одного значения разошлись бы.
---@param options table
---@param request any
---@return table
function Module.fields_of(options, request)
    local fields = {}

    if options.describe ~= nil then
        for key, value in pairs(options.describe(request) or {}) do
            fields[key] = value
        end
    end

    return fields
end

return Module
