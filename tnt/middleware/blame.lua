--- Место ошибки объявления: строка того, кто позвал вход пакета.
---
--- Незнакомое имя слоя, занятое имя, негодный фильтр, фабрика
--- не функцией — промах в строке приложения, и отказ обязан указывать
--- туда. Строка внутри пакета отправила бы искать ошибку в нём.
---
--- Но проверки стоят глубоко, и кадров от входа до них то два, то
--- десять: запись разбирает реестр, группа раскрывается в записи,
--- запись — в слой и его фильтр. Уровень `error`, посчитанный на месте
--- проверки, от этого всякий раз разный. Поэтому проверки бросают текст
--- без места (`fail.raise` из `tnt-must`), а место приписывает вход: зовёт
--- свою работу под `pcall` и бросает отказ заново уровнем того, кто
--- позвал сам вход.
---
--- Входы друг друга не зовут, а зовут работу напрямую: второй вход
--- приписал бы к отказу второе место и указал бы им на строку первого.
---
--- Брошенное не строкой уходит дальше тем же значением: у таблицы
--- и у объекта ошибки места не бывает, и `error` его не приписывает.

local Module = {}

--- Зовёт работу входа и винит в её броске того, кто позвал вход.
---
--- Зовут её отдельным предложением или присваиванием, а не хвостом:
--- хвостовой вызов снял бы кадр входа со стека, и вина ушла бы на кадр
--- дальше — к тому, кто позвал вызывающего.
---@generic R
---@param work fun(...: any): R Работа входа: бросает текст без места
---@param ... any Аргументы работы
---@return R
function Module.call(work, ...)
    local ok, result = pcall(work, ...)

    if not ok then
        -- Первый уровень — эта функция, второй — вход, третий — тот,
        -- кто позвал вход.
        error(result, 3)
    end

    return result
end

return Module
